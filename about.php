(function(){
  /* FAQ accordion */
  document.querySelectorAll('.faq-q').forEach(function(btn){
    btn.addEventListener('click', function(){
      var item = this.closest('.faq-item');
      var isOpen = item.classList.contains('faq-active');
      document.querySelectorAll('.faq-item').forEach(function(i){
        i.classList.remove('faq-active');
        i.querySelector('.faq-q').setAttribute('aria-expanded','false');
      });
      if(!isOpen){ item.classList.add('faq-active'); this.setAttribute('aria-expanded','true'); }
    });
  });

  /* Hero word reveal on load */
  document.querySelectorAll('.about-hero .word-fx').forEach(function(w, i){
    w.style.transitionDelay = (0.35 + i * 0.05) + 's';
    requestAnimationFrame(function(){ w.classList.add('in'); });
  });

  /* Parallax — hero bg + images */
  var parallaxImgs = document.querySelectorAll('[data-parallax-img]');
  var heroBg = document.querySelector('[data-parallax-bg]');
  var ticking = false;
  function applyParallax(){
    var sy = window.scrollY || window.pageYOffset;
    var vh = window.innerHeight;
    if (heroBg) heroBg.style.transform = 'translate3d(0,' + (sy * 0.35) + 'px, 0) scale(1.15)';
    parallaxImgs.forEach(function(img){
      var rect = img.getBoundingClientRect();
      if (rect.bottom < 0 || rect.top > vh) return;
      var speed = parseFloat(img.getAttribute('data-parallax-img')) || 0.15;
      var center = rect.top + rect.height / 2;
      var offset = (center - vh / 2) * speed;
      img.style.transform = 'translate3d(0,' + (-offset) + 'px,0) scale(1.12)';
    });
    ticking = false;
  }
  function onScroll(){
    if (!ticking){ requestAnimationFrame(applyParallax); ticking = true; }
  }
  window.addEventListener('scroll', onScroll, { passive: true });
  window.addEventListener('resize', applyParallax);
  applyParallax();

  /* Number counters */
  var counted = false;
  var counters = document.querySelectorAll('.count');
  function runCounters(){
    if (counted) return;
    var strip = document.querySelector('.stats-strip');
    if (!strip) return;
    var rect = strip.getBoundingClientRect();
    if (rect.top < window.innerHeight - 80){
      counted = true;
      counters.forEach(function(el){
        var target = parseInt(el.getAttribute('data-count'), 10);
        var dur = 1600, start = performance.now();
        function tick(now){
          var p = Math.min(1, (now - start) / dur);
          var eased = 1 - Math.pow(1 - p, 3);
          el.textContent = Math.round(target * eased);
          if (p < 1) requestAnimationFrame(tick);
        }
        requestAnimationFrame(tick);
      });
    }
  }
  window.addEventListener('scroll', runCounters, { passive: true });
  runCounters();

  /* Mouse-tilt on founder card */
  var fcard = document.querySelector('.founder-card');
  if (fcard){
    fcard.addEventListener('mousemove', function(e){
      var r = fcard.getBoundingClientRect();
      var x = (e.clientX - r.left) / r.width - 0.5;
      var y = (e.clientY - r.top) / r.height - 0.5;
      fcard.style.transform = 'perspective(1200px) rotateY(' + (x * 4) + 'deg) rotateX(' + (-y * 4) + 'deg)';
    });
    fcard.addEventListener('mouseleave', function(){
      fcard.style.transform = '';
    });
  }

  /* PMV tabs */
  var tabs = document.querySelectorAll('.pmv-tab');
  var panels = document.querySelectorAll('.pmv-panel');
  tabs.forEach(function(tab){
    tab.addEventListener('click', function(){
      var idx = this.getAttribute('data-pmv');
      tabs.forEach(function(t){ t.classList.remove('is-active'); t.setAttribute('aria-selected','false'); });
      panels.forEach(function(p){ p.classList.remove('is-active'); });
      this.classList.add('is-active');
      this.setAttribute('aria-selected','true');
      document.querySelector('.pmv-panel[data-pmv="'+idx+'"]').classList.add('is-active');
    });
  });
})();
</script>

